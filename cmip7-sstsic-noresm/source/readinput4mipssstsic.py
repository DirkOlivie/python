def readinput4mipssstsic(period, var, origin, year0=-10000, year1=10000, makeseasonalcycle=False):
#-----------------------
    '''
    MODIFICATIONS
        (2026-10-03) generation

    AIM 
        checking files generated by Mariana

    FILES (4)  
        siconc_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_187001-202212.nc    [before]
        siconcbcs_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_187001-202212.nc [after ]
        tos_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_187001-202212.nc       [before]  
        tosbcs_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_187001-202212.nc    [after ]

    CONTENT of FILES
        siconc    : fraction [0-100%]
        siconsbcs : fraction [0-100%]
        tos       : temperature [deg_C]
        tos       : temperature [deg_C]

    '''
    
    if   ( var == 'SSTbef' ) : readvar = 'tos'
    elif ( var == 'SSTaft' ) : readvar = 'tosbcs'
    elif ( var == 'SICbef' ) : readvar = 'siconc'
    elif ( var == 'SICaft' ) : readvar = 'siconcbcs'
    else :
        print('+++ readinput4mipssstsic +++')
        print('No var recognized : ', var)
        quit()

    if ( origin == 'input4mips-cmip7' ) :
        dir='/datalake/NS9560K/noresm3/input4mips/cmip7/PCMDI-AMIP-1-1-10'
        filename=dir+'/'+readvar+'_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_'+period+'.nc'
    else :
        print('+++ readinput4mipssstsic +++')
        print('No origin recognized : ', origin)
        quit()
    
    field=readnc.readnc(readvar,filename)
    units=readattributenc.readattributenc(readvar,filename,'units')
    latitude=readnc.readnc('lat',filename)
    longitude=readnc.readnc('lon',filename)

#   convert units : % [0-100] -> fraction [0-1]
    if ( ( readvar == 'siconc' or readvar == 'siconcbcs' ) and units == "%" ) :
        field=field / 100.
        units = "fraction"

#   time
    timelist=readnc.readnc('time', filename)
    calendar=readattributenc.readattributenc('time', filename, 'calendar')
    time_units=readattributenc.readattributenc('time', filename, 'units')

    yearlist,monthlist=timelist2yearlistmonthlist.timelist2yearlistmonthlist(timelist=timelist, time_units=time_units, calendar=calendar)

    isubset = ( yearlist >= year0 ) * ( yearlist <= year1 )

    monthlist = monthlist[isubset]
    yearlist = yearlist[isubset]     
    field = field[isubset,:,:]
    ntime,nlat,nlon=field.shape

#
#   seasonalcycle
    if ( makeseasonalcycle ) : 
        nmonth=12
        
        newfield = np.zeros((nmonth,nlat,nlon), dtype=field.dtype)

        for imonth in range(nmonth) :

            isubset = ( monthlist == ( imonth + 1 ) )

            newfield[imonth,:,:] = np.mean(field[isubset,:,:], axis=0)

        field=newfield
        monthlist=monthlist[0:nmonth]
        yearlist=yearlist[0:nmonth]


    
    data = {'variable' : var, \
            'field' : field, \
            'units' : units,\
            'latitude' : latitude, \
            'longitude' : longitude, \
            'yearlist' : yearlist, \
            'monthlist': monthlist, \
            'ntime' : len(yearlist) \
           }

    return data             
