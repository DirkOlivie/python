def readnoresmsstsic(period, var, origin, year0=-10000, year1=10000):
#-------------------
    '''
    MODIFICATIONS
        (2026-10-03) generation

    AIM 
        checking files generated by Mariana

    NEW FILES (4)
        187001-202212 : sst_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_187001-202212_c20260924.nc
        piclimo : sst_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_piclimo_c20260924.nc (probably 1870-1899 average)
        2000climo : sst_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_2000climo_c20260924.nc
        2010climo : sst_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_2010climo_c20260924.nc

    OLDER FILES
        fice-micom-divocn_sst-micom-dow_N1850_f19_tn14_20190621_1751-1780_series_version20190726_clim.nc
        fice-micom-divocn_sst-micom-dow_NHIST_f19_tn14_20190625_1849-2015_series_version20190726_ts.nc


    CONTENT of FILES
        ice_cov           : fraction [0-1]
        ice_cov_prediddle : fraction [0-1]
        SST_cpl           : temperature [deg_C]
        SST_cpl_prediddle : temperature [deg_C]

    '''
    
    if   ( var == 'SSTbef' ) : readvar = 'SST_cpl_prediddle'
    elif ( var == 'SSTaft' ) : readvar = 'SST_cpl'
    elif ( var == 'SICbef' ) : readvar = 'ice_cov_prediddle'
    elif ( var == 'SICaft' ) : readvar = 'ice_cov'
    else :
        print('+++ readnoresmsstsic +++')
        print('No var recognized : ', var)
        quit()

    if ( origin == 'input4mips-cmip7' ) :
        dir = '/scratch/olivie/noresm-inputdata/atm/cam/sst'
        filename = dir+'/sst_input4MIPs_SSTsAndSeaIce_CMIP_PCMDI-AMIP-1-1-10_gn_'+period+'_c20260924.nc'
    elif ( origin == 'noresm2' ) :
        dir='/scratch/olivie/noresm-inputdata/noresm-only/atm/cam/sst'
        filename=dir+'/fice-micom-divocn_sst-micom-dow_'+period+'.nc'
    else :
        print('+++ readnoresmsstsic +++')
        print('No origin recognized : ', origin)
        quit()
    
    field=readnc.readnc(readvar,filename)
    units=readattributenc.readattributenc(readvar,filename,'units')
    latitude=readnc.readnc('lat',filename)
    longitude=readnc.readnc('lon',filename)

    datelist=readnc.readnc('date', filename)

    yearlist= datelist // 10000
    monthlist = ( datelist % 10000 ) // 100

    isubset = ( yearlist >= year0 ) * ( yearlist <= year1 )

    monthlist = monthlist[isubset]
    yearlist = yearlist[isubset]     
    field = field[isubset,:,:]
    
    data = {'variable' : var, \
            'field' : field, \
            'units' : units,\
            'latitude' : latitude, \
            'longitude' : longitude, \
            'yearlist' : yearlist, \
            'monthlist': monthlist, \
            'ntime' : len(yearlist) \
           }

    return data             
